# Arithmetic Operators

number1 = 10
number2 = 3

print(number1 + number2)
print(number1 - number2)
print(number1 * number2)
print(number1 / number2)
print(number1 // number2)
print(number1 % number2)
print(number1 ** number2)


# Comparison Operators

age = 32

print(age == 32)
print(age != 20)
print(age > 18)
print(age < 18)
print(age >= 32)
print(age <= 30)


# Logical Operators

age = 25
has_ticket = True

print(age >= 18 and has_ticket)

has_cash = False
has_card = True

print(has_cash or has_card)

is_closed = False

print(not is_closed)


# Assignment Operators

number = 10

number += 5
print(number)

number -= 3
print(number)

number *= 2
print(number)

number /= 4
print(number)

number //= 2
print(number)

number %= 2
print(number)

number **= 3
print(number)


# Parentheses and Operation Order

result1 = 10 + 5 * 2
result2 = (10 + 5) * 2

print(result1)
print(result2)


# Operators with Strings

first_name = "Osman"
last_name = "Bozok"

full_name = first_name + " " + last_name

print(full_name)

word = "Python"

print(word * 3)


# Assignment vs Comparison

age = 32

print(age == 32)