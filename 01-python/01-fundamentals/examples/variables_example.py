# Basic variable assignment

name = "Osman"
age = 32
city = "Podgorica"

print(name)
print(age)
print(city)


# Changing a variable's value

age = 33

print(age)


# Multiple assignment

name, age, city = "Osman", 32, "Podgorica"

print(name)
print(age)
print(city)


# Variables can be used in expressions

number1 = 10
number2 = 20

total = number1 + number2

print(total)


# Variables can be used with f-strings

name = "Osman"
age = 32

print(f"My name is {name} and I am {age} years old.")
